"""The paper's main experiment, at scale.

Design. Three evaluation groups: real attacks, legitimate-but-alarming requests generated by the
documented procedure in `probes.py`, and ordinary legitimate requests. Every detector is
unsupervised, fitted only on normal traffic, and given a threshold calibrated on a labelled
held-out split, which is a supervised advantage it would not have in deployment.

Splits are disjoint: the requests the probes are derived from are held out of the fitting set, so
no probe's base request was seen during fitting.

Reported per detector: the alert rate on each group, and the separation between real attacks and
legitimate-but-alarming traffic. The latter is the quantity standard evaluations cannot express,
because standard corpora contain no legitimate-but-alarming category.

    ./.venv/bin/python run_scaled_experiment.py [n_group] [n_fit]
"""
from __future__ import annotations

import collections
import json
import os
import sys

import numpy as np

from zeroday_verify.baselines import PAYL, KruegelVignaICD
from zeroday_verify.data_text import load_csic, parse_request, serialize_http
from zeroday_verify.probes import generate

OUT = "results/paper"
GROUPS = (("attack", "real attacks"), ("probe", "legitimate-alarming"),
          ("ordinary", "ordinary legitimate"))


def icd(text: str, n: int = 32) -> np.ndarray:
    """Sorted character-frequency profile computed over the WHOLE request.

    NOT the Kruegel & Vigna detector. Their design learns a character-distribution model per
    (server-side program, parameter) and sets a threshold per model; this function collapses the
    request into a single global profile. An earlier version of this script labelled it as their
    method, which was wrong: the two behave very differently, and the per-resource design is
    precisely what avoids the failure mode a global profile exhibits. The faithful implementation
    lives in `zeroday_verify.baselines.KruegelVignaICD` and is used below for comparison.
    """
    if not text:
        return np.zeros(n)
    c = np.zeros(256)
    for ch in text.encode("utf-8", "ignore"):
        c[ch] += 1
    c = np.sort(c)[::-1][:n]
    t = c.sum()
    return c / t if t else c


def main(n_group: int = 300, n_fit: int = 2000) -> None:
    os.makedirs(OUT, exist_ok=True)
    from sklearn.decomposition import PCA
    from sklearn.ensemble import IsolationForest
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.metrics import roc_curve
    from sklearn.svm import OneClassSVM

    need_n = n_fit + 3 * n_group + 1500
    df = load_csic("data/raw_text/csic_all.parquet", n_normal=need_n,
                   n_anomalous=2 * n_group + 1500, seed=17)
    norm = [str(r) for r in df[df["label"] == 0]["requests"]]
    atk = [str(r) for r in df[df["label"] == 1]["requests"]]
    rng = np.random.RandomState(17)
    rng.shuffle(norm); rng.shuffle(atk)

    fit_n = norm[:n_fit]                                   # fit the normality models
    cal_n = norm[n_fit:n_fit + 500]                        # calibrate thresholds
    ord_n = norm[n_fit + 500:n_fit + 500 + n_group]        # ordinary legitimate group
    base_n = norm[n_fit + 500 + n_group:]                  # probes derive from here only
    cal_a, ev_a = atk[:500], atk[500:500 + n_group]

    probes = generate(base_n, n_group)
    cats = collections.Counter(p.category for p in probes)
    print(f"fit {len(fit_n)} | calibrate {len(cal_n)}+{len(cal_a)} | "
          f"eval: attacks {len(ev_a)}, probes {len(probes)}, ordinary {len(ord_n)}")
    print("probe categories:", dict(cats))

    txt = lambda r: serialize_http(parse_request(r))                          # noqa: E731
    RAW = {"fit": fit_n, "cal_n": cal_n, "cal_a": cal_a, "attack": ev_a,
           "probe": [p.raw_request for p in probes], "ordinary": ord_n}
    T = {k: [txt(r) for r in v] for k, v in RAW.items()}

    vec = TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5), max_features=3000)
    Xfit = vec.fit_transform(T["fit"]).toarray()
    enc = lambda ts: vec.transform(ts).toarray()                              # noqa: E731
    print("fitting detectors ...", flush=True)
    kv = KruegelVignaICD().fit(RAW["fit"])
    payl = PAYL().fit(RAW["fit"])
    print(f"  Kruegel/Vigna: {len(kv.models)} per-(path,attribute) models")
    sub = Xfit[rng.choice(len(Xfit), min(1500, len(Xfit)), replace=False)]
    ocs = OneClassSVM(kernel="rbf", gamma="scale", nu=0.05).fit(sub)
    iso = IsolationForest(n_estimators=200, random_state=17).fit(Xfit)
    pca = PCA(n_components=32, random_state=17).fit(Xfit)

    # published detectors consume the raw request; generic ones consume the serialised text
    detectors = {
        "char-distribution (Kruegel & Vigna 2003)": ("raw", kv.score),
        "PAYL byte frequency (Wang & Stolfo 2004)": ("raw", payl.score),
        "one-class SVM (char n-gram)": ("txt", lambda ts: -ocs.decision_function(enc(ts))),
        "isolation forest (char n-gram)": ("txt", lambda ts: -iso.score_samples(enc(ts))),
        "PCA reconstruction error":
            ("txt", lambda ts: np.linalg.norm(
                enc(ts) - pca.inverse_transform(pca.transform(enc(ts))), axis=1)),
    }

    out = {"n": {g: len(T[g]) for g, _ in GROUPS}, "probe_categories": dict(cats),
           "detectors": {}}
    print(f"\n{'detector':42s} {'attacks':>8s} {'legit-alarm':>12s} {'ordinary':>9s} "
          f"{'separation':>11s}  ordering")
    for name, (kind, fn) in detectors.items():
        src = RAW if kind == "raw" else T
        s_cn, s_ca = fn(src["cal_n"]), fn(src["cal_a"])
        fpr, tpr, th = roc_curve([0] * len(s_cn) + [1] * len(s_ca),
                                 np.concatenate([s_cn, s_ca]))
        t = float(th[int(np.argmax(tpr - fpr))])
        rates, meds, per_cat = {}, {}, {}
        for g, _ in GROUPS:
            s = fn(src[g])
            rates[g] = round(float((s >= t).mean()), 3)
            meds[g] = round(float(np.median(s)), 4)
        s_p = fn(src["probe"])
        for c in cats:
            m = [i for i, p in enumerate(probes) if p.category == c]
            per_cat[c] = round(float((s_p[m] >= t).mean()), 3)
        sep = round(rates["attack"] - rates["probe"], 3)
        order = "INVERTED" if meds["probe"] > meds["attack"] else "ordered"
        out["detectors"][name] = {"rates": rates, "medians": meds, "separation": sep,
                                  "ordering": order, "per_category": per_cat}
        print(f"{name:42s} {rates['attack']:8.2f} {rates['probe']:12.2f} "
              f"{rates['ordinary']:9.2f} {sep:11.2f}  {order}")

    with open(f"{OUT}/main_experiment.json", "w") as fh:
        json.dump(out, fh, indent=2)
    print(f"\nwrote {OUT}/main_experiment.json")


if __name__ == "__main__":
    a = int(sys.argv[1]) if len(sys.argv) > 1 else 300
    b = int(sys.argv[2]) if len(sys.argv) > 2 else 2000
    main(a, b)
